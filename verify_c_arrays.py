"""Verify runtime byte indexing through the guest C compiler."""
import secrets
import struct
import sys
import tempfile
from pathlib import Path

from guest_tool import Guest
from verify_c_functions import calls, generated_code
from verify_shell import command, read_prompt
from verify_source_import import receive


def main():
    root = Path(".local/c-array-check")
    root.mkdir(parents=True, exist_ok=True)
    workspace = Path(tempfile.mkdtemp(dir=root)).resolve()
    (workspace / "guest.hex").write_text(Path(sys.argv[1]).read_text())
    compiler = Path(sys.argv[2]).read_bytes().strip()
    guest = Guest(workspace)
    bias = secrets.randbelow(20) + 8
    size = secrets.randbelow(9) + 8
    with tempfile.TemporaryDirectory(dir="/tmp") as temp:
        socket = Path(temp) / "qmp.sock"
        try:
            guest.boot(disk=True, observer_socket=socket)
            read_prompt(guest)
            receive(guest, b"compiler", compiler)
            command(guest, b"as compiler", b"assembled\n")
            command(guest, b"install", b"installed\n")
            source = (
                "int g(int x){return x+1;} "
                f"int f(int x){{char a[{size}];"
                f"a[g(x)]=x+{bias}; a[x]=g(x)*2;"
                "return a[x]*3+a[g(x)];}"
            )
            receive(guest, b"source", source.encode())
            command(guest, b"build source", b"built\n")
            code = generated_code(guest, socket)
            words = [word for word, in struct.iter_unpack("<I", code)]
            has_byte_store = any(word & 0xfec00000 == 0x38000000 for word in words)
            has_byte_load = any(word & 0xfec00000 == 0x38400000 for word in words)
            if not (has_byte_store and has_byte_load):
                raise ValueError("Missing generated byte load or store")
            if len(calls(code)) != 3:
                raise ValueError("Expected calls in both indices and assigned values")
            for x in (0, size - 2, secrets.randbelow(size - 3) + 1):
                result = 7*x + 6 + bias
                command(guest, f"run {x}".encode(), f"exit {result:08x}\n".encode())
            if generated_code(guest, socket) != code:
                raise ValueError("Generated code changed between runtime inputs")

            for invalid in (
                b"int f(int x){char a[0];return x;}",
                b"int f(int x){return a[x];}",
                b"int f(int x){char a[8];a[x=1;return x;}",
            ):
                receive(guest, b"source", invalid)
                command(guest, b"build source", b"build error\n")
                if generated_code(guest, socket) != code:
                    raise ValueError("Rejected source replaced the previous program")

            receive(guest, b"source", b"int f(int x){char a[1];a[0]=x;return a[0];}")
            command(guest, b"build source", b"built\n")
            command(guest, b"run 65", b"exit 00000041\n")
        finally:
            guest.stop()
    print(f"C arrays verified: {workspace}")


if __name__ == "__main__":
    main()
