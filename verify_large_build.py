"""Check full-capacity builds, installation and process I/O in the same VM.

Usage: verify_large_build.py IMAGE CAPACITY PROGRAM_ADDRESS COMPILER_ADDRESS
"""
import secrets
import sys
import tempfile
from pathlib import Path

from guest_tool import Guest
from observer_qmp import read_memory
from verify_process_io import application
from verify_shell import command, read_prompt
from verify_source_import import receive


COMPILER = (
    "mov x5,x3;mov w8,0;mov w10,w4;count:;cmp w10,4;b.lt counted;"
    "sub w10,w10,4;add w8,w8,1;b count;counted:;sub w8,w8,2;"
    "mov w9,5120;lsl w9,w9,16;orr w8,w8,w9;str w8,[x5];add x5,x5,4;"
    "mov w9,54879;lsl w9,w9,16;add w9,w9,960;sub w8,w4,12;"
    "fill:;str w9,[x5];add x5,x5,4;sub w8,w8,4;cmp w8,0;b.ne fill;"
    "mov w7,4352;lsl w7,w7,16;mov w8,7200;orr w7,w7,w8;"
    "str w7,[x5];str w9,[x5,4];mov w0,w4;ret;"
).encode()


def main():
    image = Path(sys.argv[1])
    capacity = int(sys.argv[2], 0)
    program_address, compiler_address = (int(value, 0) for value in sys.argv[3:5])
    root = Path(".local/large-build-check")
    root.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(dir=root)).resolve()
    (work / "guest.hex").write_bytes(image.read_bytes())
    guest = Guest(work)
    first = bytes(65 + secrets.randbelow(13) for _ in range(3))
    second = bytes(110 + secrets.randbelow(13) for _ in range(3))
    with tempfile.TemporaryDirectory(dir="/tmp") as temp:
        socket = Path(temp) / "qmp.sock"
        try:
            guest.boot(disk=True, observer_socket=socket)
            read_prompt(guest)
            receive(guest, b"tool", COMPILER)
            receive(guest, b"input", b"go")
            command(guest, b"as tool", b"assembled\n")
            command(guest, b"install", b"installed\n")
            for _ in range(2):
                command(guest, b"build input", b"built\n")
                size = read_memory(socket, 0x41100004, 4, work / "size.bin")
                if int.from_bytes(size, "little") != capacity:
                    raise ValueError("Compiler did not receive the declared capacity")
                command(guest, b"run 71", b"exit 0000004e\n")
            generated = read_memory(socket, program_address, capacity, work / "generated.bin")
            command(guest, b"install", b"installed\n")
            installed = read_memory(socket, compiler_address, capacity, work / "installed.bin")
            if generated != installed:
                raise ValueError("Full-capacity installation changed generated bytes")
            command(guest, b"run 71", b"exit 0000004e\n")

            for index, data in enumerate((first, second), 1):
                name = f"f{index}".encode()
                receive(guest, name, data)
                receive(guest, b"proc", application(name))
                command(guest, b"as proc", b"assembled\n")
                command(guest, f"spawn {index + 10}".encode(), f"pid {index}\n".encode())
            guest.serial_send(b"schedule\n".hex())
            output = read_prompt(guest)
            if first[:1] + second[:1] + first[1:] + second[1:] not in output:
                raise ValueError("Process file I/O failed after a full-capacity installation")
            command(guest, b"wait 1", b"exit 0000000b\n")
            command(guest, b"wait 2", b"exit 0000000c\n")
        finally:
            guest.stop()
    print(f"Full-capacity build/install and process I/O verified: {capacity} bytes, {work}")


if __name__ == "__main__":
    main()
